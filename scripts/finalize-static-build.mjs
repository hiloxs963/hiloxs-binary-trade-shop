import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { copyFile, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  CLIENT_DIR,
  SITE_ORIGIN,
  listFiles,
  parseSitemap,
  readHtmlFiles,
} from "./static-build-lib.mjs";

const indexPath = path.join(CLIENT_DIR, "index.html");
await copyFile(indexPath, path.join(CLIENT_DIR, "_shell.html"));

const indexHtml = await readFile(indexPath, "utf8");
const stylesheet = indexHtml.match(
  /<link[^>]+rel=["']stylesheet["'][^>]+href=["']([^"']+)["']/i,
)?.[1];
if (!stylesheet) throw new Error("Cannot identify the production stylesheet for 404.html");

const notFoundHtml = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex, nofollow">
  <title>Page Not Found | HILOXS</title>
  <link rel="stylesheet" href="${stylesheet}">
  <link rel="icon" href="/favicon.png" type="image/png">
</head>
<body>
  <main class="flex min-h-screen items-center justify-center bg-background px-4">
    <div class="max-w-md text-center">
      <h1 class="text-7xl font-bold text-foreground">404</h1>
      <h2 class="mt-4 text-xl font-semibold text-foreground">Page not found</h2>
      <p class="mt-2 text-sm text-muted-foreground">The page you requested does not exist.</p>
      <a class="mt-6 inline-flex rounded-md bg-primary px-4 py-2 text-primary-foreground" href="/">Go home</a>
    </div>
  </main>
</body>
</html>
`;
await writeFile(path.join(CLIENT_DIR, "404.html"), notFoundHtml);

// CSP spec §8.2: when a directive contains hash or nonce values, 'unsafe-inline' is silently
// ignored by the browser — hashes and 'unsafe-inline' are mutually exclusive. script-src must
// therefore carry NO hashes. Hashes are not viable here anyway: the TanStack Start
// $tsr-stream-barrier script embeds Date.now() at SSR time, making its body byte-unstable
// across builds. style-src: React injects inline styles at runtime; they cannot be hashed on
// a static host with no per-request nonce.
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "img-src 'self' https://api.hiloxs.co.ke",
  "connect-src 'self' https://api.hiloxs.co.ke",
  "object-src 'none'",
  "base-uri 'self'",
  "frame-ancestors 'none'",
  "form-action 'self'",
  "manifest-src 'self'",
  "worker-src 'self'",
].join("; ");

const htaccess = `# Generated by scripts/finalize-static-build.mjs. Do not edit the artifact by hand.
RewriteEngine On

# Canonicalize the only verified public origin. Query strings are preserved.
RewriteCond %{HTTPS} !=on [OR]
RewriteCond %{HTTP_HOST} ^www\\.hiloxs\\.co\\.ke$ [NC]
RewriteRule ^ https://hiloxs.co.ke%{REQUEST_URI} [R=308,L,NE]

<IfModule mod_headers.c>
  Header always set Content-Security-Policy "${csp}"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), geolocation=(), microphone=(), payment=(), usb=()"
  Header always set X-Frame-Options "DENY"
  Header always set Strict-Transport-Security "max-age=31536000" "expr=%{HTTPS} == 'on'"
  Header always unset X-Powered-By

  SetEnvIf Request_URI "^/_build/" immutable_asset
  Header set Cache-Control "public, max-age=31536000, immutable" env=immutable_asset
  <FilesMatch "\\.(?:html|xml|txt)$">
    Header set Cache-Control "no-cache, no-store, must-revalidate"
  </FilesMatch>
</IfModule>

# Preserve client-side access to known private routes without exposing them in the sitemap.
# shop/<slug> is included because only the static product list is prerendered: a seller product
# activated after the build has no HTML file, so a direct load or refresh would otherwise hit the
# catch-all 404 below. The client route resolves the slug against the API and renders its own
# not-found for a bogus one, so this serves the shell rather than masking a genuine miss.
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^(?:login|register|forgot-password|reset-password|verify-email|checkout|my-orders|sell-with-us|staff|account/security|shop/[^/]+)/?$ _shell.html [L]

# Existing prerendered routes and static assets are served directly. Everything else is a real 404.
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^ - [R=404,L]
ErrorDocument 404 /404.html
`;
await writeFile(path.join(CLIENT_DIR, ".htaccess"), htaccess);

const sitemap = await readFile(path.join(CLIENT_DIR, "sitemap.xml"), "utf8");
const urls = parseSitemap(sitemap);
if (urls.some((url) => !url.startsWith(`${SITE_ORIGIN}/`))) {
  throw new Error("Sitemap contains a non-canonical origin");
}

const commit =
  process.env.GITHUB_SHA?.match(/^[0-9a-f]{40}$/i)?.[0] ??
  execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const checksums = {};
for (const file of await listFiles()) {
  if (file.endsWith("release-manifest.json")) continue;
  const relative = path.relative(CLIENT_DIR, file).split(path.sep).join("/");
  checksums[relative] = createHash("sha256")
    .update(await readFile(file))
    .digest("hex");
}
await writeFile(
  path.join(CLIENT_DIR, "release-manifest.json"),
  `${JSON.stringify({ schemaVersion: 1, commit, checksums }, null, 2)}\n`,
);

await import("./verify-static-build.mjs");
